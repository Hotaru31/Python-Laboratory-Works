a = float(input("Введите ненулевое число A: "))
b = float(input("Введите ненулевое число B: "))

if a == 0 or b == 0:
    print("Числа должны быть ненулевыми.")
else:
    x = abs(a)
    y = abs(b)

    print("Сумма модулей:", x + y)
    print("Разность модулей:", x - y)
    print("Произведение модулей:", x * y)
    print("Частное модулей:", x / y)