a = float(input("Введите ненулевое число A: "))
b = float(input("Введите ненулевое число B: "))

if a == 0 or b == 0:
    print("Числа должны быть ненулевыми.")
else:
    x = a ** 2
    y = b ** 2

    print("Сумма квадратов:", x + y)
    print("Разность квадратов:", x - y)
    print("Произведение квадратов:", x * y)
    print("Частное квадратов:", x / y)